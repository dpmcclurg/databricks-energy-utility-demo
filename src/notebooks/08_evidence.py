def md_table(df: pd.DataFrame) -> str:
    df = df.copy()
    for c in df.columns:
        if pd.api.types.is_float_dtype(df[c]):
            df[c] = df[c].map(lambda v: "" if pd.isna(v) else f"{v:,.4f}".rstrip("0").rstrip("."))
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join("" if pd.isna(v) else str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


def q(sql: str) -> pd.DataFrame:
    return spark.sql(sql).toPandas()


def write(name: str, title: str, sections: list) -> None:
    if FILES and name not in FILES:
        return
    body = [f"# {title}", "", f"Run: batch `{BATCH}`, as of `{AS_OF}`. Generated by `src/notebooks/08_evidence.py` from the tables.", ""]
    for heading, text in sections:
        body += [f"## {heading}", "", text, ""]
    text = "\n".join(body).replace(CATALOG, "<catalog>")
    with open(f"{OUT}/{name}", "w") as f:
        f.write(text)
    print(text[:3000])

